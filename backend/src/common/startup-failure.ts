const ledgerCodes = new Set(['UNKNOWN_DATABASE_MIGRATION', 'DATABASE_MIGRATION_PENDING',
  'DATABASE_MIGRATION_CHECKSUM_REQUIRED', 'DATABASE_MIGRATION_CHANGED']);
const secretFileCode = /^PRODUCTION_(?:DATABASE_URL|JWT_ACCESS_SECRET|CRYPTO_PROVIDER_TOKEN|SMTP_PASSWORD|ACCOUNT_ACTION_KEY|BOOTSTRAP_ADMIN_PASSWORD|MFA_ENCRYPTION_KEY|OIDC_CLIENT_SECRET|OIDC_STORAGE_KEY)_(?:USE_FILE|FILE_REQUIRED|FILE_INVALID)$/;

export function startupFailure(error: unknown) {
  let code = 'APPLICATION_STARTUP_FAILED';
  if (error instanceof Error) {
    const message = error.message;
    const [prefix] = message.split(':', 1);
    if (ledgerCodes.has(prefix)) code = prefix;
    else if (codes.has(message) || secretFileCode.test(message)) code = message;
    else if (message === 'SMTP_FROM is required when SMTP_ENABLED=true') code = 'SMTP_FROM_REQUIRED';
    else if (message === 'SMTP_HOST is required when SMTP_ENABLED=true') code = 'SMTP_HOST_REQUIRED';
    else if ('code' in error && error.code === 'EADDRINUSE') code = 'APPLICATION_PORT_IN_USE';
    else if ('code' in error && error.code === 'ERR_SOCKET_BAD_PORT') code = 'APPLICATION_PORT_INVALID';
  }
  return { event: code === 'SMTP_VERIFY_FAILED' ? 'email.smtp_verify_failed' : 'application.startup_failed', code };
}
